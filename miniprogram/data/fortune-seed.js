function pick(arr, idx) {
  return arr[idx % arr.length]
}

function generateFortunes() {
  const result = []
  for (const type of ALL_TYPES) {
    const traits = TYPE_TRAITS[type]
    for (let i = 0; i < 60; i++) {
      const template = TEMPLATES[i % TEMPLATES.length]
      const message = template
        .replace('{trait}', pick(traits.trait, i))
        .replace('{style}', pick(traits.style, i + 3))
        .replace('{mood}', pick(traits.mood, i + 7))
        .replace('{aspect}', pick(traits.aspect, i + 5))
        .replace('{action}', pick(traits.action, i + 2))
        .replace('{tip}', pick(traits.tip, i + 11))

      const typeIdx = ALL_TYPES.indexOf(type)
      result.push({
        _id: `${type}_${i}`,
        type,
        index: i,
        message,
        luckyColor: LUCKY_COLORS[(i * 7 + typeIdx * 3) % LUCKY_COLORS.length],
        keywords: [
          KEYWORDS_POOL[(i * 3 + typeIdx) % KEYWORDS_POOL.length],
          KEYWORDS_POOL[(i * 3 + typeIdx + 13) % KEYWORDS_POOL.length],
          KEYWORDS_POOL[(i * 3 + typeIdx + 29) % KEYWORDS_POOL.length],
        ]
      })
    }
  }
  return result
}

