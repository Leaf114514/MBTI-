// ----------------------------------------------------------
//  工具：将 SVG Path 构建为 Data URI
//  可用于 <image> 的 src 属性，避免额外图片文件
//  @param {string} pathData — SVG d 属性值
//  @param {string} color    — fill 颜色（如 "#999"）
//  @returns {string} data:image/svg+xml,... 格式的 URI
// ----------------------------------------------------------
function buildSvgDataUri(pathData, color) {
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><path d="' + pathData + '" fill="' + color + '"/></svg>'
  return 'data:image/svg+xml,' + encodeURIComponent(svg)
}

// ----------------------------------------------------------
//  Tab 配置表
//  - pagePath: 页面路径（对应 app.json 中 tabBar.list）
//  - text:     底部文字
//  - icon:     对应 SVG_PATHS 的键名
// ----------------------------------------------------------
const TAB_LIST = [
  { pagePath: '/page/home/index', text: '主页', icon: 'home' },
  { pagePath: '/page/mbti/index', text: '故事', icon: 'story' },
  { pagePath: '/page/profile/index', text: '我的', icon: 'profile' },
]

Component({
  // ----------------------------------------------------------
  //  组件数据
  //  - selected:   当前选中 Tab 索引
  //  - themeColor: 主题色（影响图标 active 态颜色）
  //  - tabList:    渲染用的 Tab 列表（含 graySrc/colorSrc/active）
  // ----------------------------------------------------------
  data: {
    selected: 0,
    themeColor: '#e74c3c',
    darkMode: false,
    tabList: [],
  },

  lifetimes: {
    // 组件挂载时：生成初始图标 Data URI
    attached() {
      this._updateIcons()
    },
  },

  // ----------------------------------------------------------
  //  所在页面的生命周期（自小程序基础库 2.2.3 起可用）
  //  页面每次显示时检查主题色是否变化，按需更新图标
  // ----------------------------------------------------------
  pageLifetimes: {
    show() {
      const app = getApp()
      const themeColor = app.globalData.themeColor || '#e74c3c'
      if (themeColor !== this.data.themeColor) {
        this.setData({ themeColor })
        this._updateIcons()
      }
    },
  },

  methods: {
    // ----------------------------------------------------------
    //  生成每项的灰色/彩色 SVG Data URI
    //  避免在 WXML 中用复杂逻辑动态切换图片
    // ----------------------------------------------------------
    _updateIcons() {
      const { themeColor, selected, darkMode } = this.data
      const grayColor = darkMode ? 'rgba(255,255,255,0.35)' : '#999999'
      const tabList = TAB_LIST.map((tab, index) => ({
        ...tab,
        graySrc: buildSvgDataUri(SVG_PATHS[tab.icon], darkMode ? '#555555' : '#999999'),
        colorSrc: buildSvgDataUri(SVG_PATHS[tab.icon], themeColor),
        active: index === selected,
      }))
      this.setData({ tabList })
    },

    // ----------------------------------------------------------
    //  Tab 点击处理
    //  1. 防止重复点击同一 Tab
    //  2. 记录切换方向（供页面 slide 动画使用）
    //  3. 调用 wx.switchTab 跳转
    // ----------------------------------------------------------
    onTabTap(e) {
      const index = e.currentTarget.dataset.index
      if (index === this.data.selected) return  // 点击当前 Tab，忽略

      const app = getApp()
      const prevIndex = this.data.selected
      // 记录切换方向：索引变大 = 向右滑，变小 = 向左滑
      app.globalData.tabSwitchDirection = index > prevIndex ? 'right' : 'left'

      const tab = TAB_LIST[index]
      this.setData({ selected: index })
      wx.switchTab({ url: tab.pagePath })
    },
  },

  // ----------------------------------------------------------
  //  数据监听器：selected 变化时重新生成图标着色
  // ----------------------------------------------------------
  observers: {
    selected() {
      this._updateIcons()
    },
    darkMode() {
      this._updateIcons()
    },
  },
})