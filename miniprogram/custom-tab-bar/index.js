function buildSvgDataUri(pathData, color) {
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><path d="' + pathData + '" fill="' + color + '"/></svg>'
  return 'data:image/svg+xml,' + encodeURIComponent(svg)
}

const TAB_LIST = [
  { pagePath: '/page/home/index', text: '主页', icon: 'home' },
  { pagePath: '/page/mbti/index', text: '故事', icon: 'story' },
  { pagePath: '/page/profile/index', text: '我的', icon: 'profile' },
]

Component({
  data: {
    selected: 0,
    themeColor: '#e74c3c',
    tabList: [],
  },

  lifetimes: {
    attached() {
      this._updateIcons()
    },
  },

  pageLifetimes: {
    show() {
      const app = getApp()
      const themeColor = app.globalData.themeColor || '#e74c3c'
      if (themeColor !== this.data.themeColor) {
        this.setData({ themeColor })
        this._updateIcons()
      }
    },
  },

  methods: {
    _updateIcons() {
      const { themeColor, selected } = this.data
      const tabList = TAB_LIST.map((tab, index) => ({
        ...tab,
        graySrc: buildSvgDataUri(SVG_PATHS[tab.icon], '#999999'),
        colorSrc: buildSvgDataUri(SVG_PATHS[tab.icon], themeColor),
        active: index === selected,
      }))
      this.setData({ tabList })
    },

    onTabTap(e) {
      const index = e.currentTarget.dataset.index
      if (index === this.data.selected) return

      const app = getApp()
      const prevIndex = this.data.selected
      app.globalData.tabSwitchDirection = index > prevIndex ? 'right' : 'left'

      const tab = TAB_LIST[index]
      this.setData({ selected: index })
      wx.switchTab({ url: tab.pagePath })
    },
  },

  observers: {
    selected() {
      this._updateIcons()
    },
  },
})
